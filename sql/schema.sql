CREATE SCHEMA IF NOT EXISTS project1;

CREATE TABLE project1.district (
    district_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en text NOT NULL UNIQUE CHECK (btrim(name_en) <> '')
);
CREATE TABLE project1.station (
    station_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id integer NOT NULL REFERENCES project1.district ON DELETE RESTRICT,
    name_zh text NOT NULL CHECK (btrim(name_zh) <> ''),
    name_en text NOT NULL CHECK (btrim(name_en) <> ''),
    lon_mdeg integer CHECK (lon_mdeg BETWEEN -180000 AND 180000),
    lat_mdeg integer CHECK (lat_mdeg BETWEEN -90000 AND 90000),
    UNIQUE (name_zh, district_id),
    CHECK ((lon_mdeg IS NULL) = (lat_mdeg IS NULL))
);
CREATE TABLE project1.metro_line (
    line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_zh text NOT NULL UNIQUE CHECK (btrim(name_zh) <> ''),
    name_en text NOT NULL UNIQUE CHECK (btrim(name_en) <> '')
);
CREATE TABLE project1.line_station (
    line_id integer NOT NULL REFERENCES project1.metro_line ON DELETE RESTRICT,
    station_id integer NOT NULL REFERENCES project1.station ON DELETE RESTRICT,
    position integer NOT NULL CHECK (position > 0),
    status text NOT NULL CHECK (status IN ('Operation', 'Construction')),
    opening_year smallint NOT NULL CHECK (opening_year BETWEEN 1900 AND 2200),
    first_train time(0), last_train time(0),
    PRIMARY KEY (line_id, station_id),
    CONSTRAINT line_station_position_uq UNIQUE (line_id, position) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE project1.station_exit (
    exit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id integer NOT NULL REFERENCES project1.station ON DELETE CASCADE,
    exit_code text NOT NULL CHECK (btrim(exit_code) <> ''),
    UNIQUE (station_id, exit_code)
);
CREATE TABLE project1.exit_landmark (
    exit_id integer NOT NULL REFERENCES project1.station_exit ON DELETE CASCADE,
    landmark_name text NOT NULL CHECK (btrim(landmark_name) <> ''),
    PRIMARY KEY (exit_id, landmark_name)
);
